// 서비스 이름 — **여기 한 곳에서만 나온다** (MD-P-2026-057 §A).
//
// ── 왜 상수인가 ────────────────────────────────────────────────────
//
// 이름이 화면마다 문자열로 적혀 있으면 다음에 또 바뀔 때 열두 군데를 다시
// 찾아야 하고, 한 군데를 빠뜨리면 한 서비스에 두 이름이 돌아다닌다.
// 실제로 「미션덱 / Mission Deck / MISSION DECK」 세 표기가 섞여 있었다.
//
// ── 왜 둘인가 ──────────────────────────────────────────────────────
//
// 자리마다 폭이 다르다. 하나로 쓰면 어디선가 잘리거나 넘친다.
//   · 긴 이름 — 사람이 처음 만나거나 여백이 있는 자리 (로고 넷)
//   · 짧은 이름 — 좁거나 **문장 안에 끼는** 자리 (<title> · 푸터 · 안내문)
//
// ── 이름은 표시에만 쓴다 ───────────────────────────────────────────
//
// 판정·식별에는 절대 쓰지 않는다 (§G 「이름으로 판정하지 않는다」). 경로
// `/v3` · 클래스 `.v3-*` · 설정 열쇠 `ui_v3_enabled` · 외부로 나가는
// User-Agent `MissionDeck/1.0` · `external_link.meta` 의 표식
// `createdByMissionDeck` 은 **이 상수와 무관하며 바뀌지 않는다.**
// 그래서 이름을 갈아 끼우는 일이 화면 문자열 교체로 끝난다.

/** 조직 이름. `<title>` 끝에 붙는다. 이번 회차에서 값은 안 바뀐다. */
