// 화면 기본값 — **사용자의 속성이다** (MD-P-2026-031 §C 회신 5 · ⓑ).
//
// ── 왜 있는가 ────────────────────────────────────────────────────
//
// 「내 업무」로 들어간다는 것은 **담당이 나이고 영역이 내 영역**이라는 뜻이다.
// 그 두 값을 화면이 `/api/meta/selectors` 응답을 기다려 알아내고 있었다. 그래서
// "영역 기본값이 정해졌는가"를 세는 게이트(`areaDefaulted`)가 필요했고, 그 게이트가
// §C3·§C4 로 화면이 넷이 되면 **네 곳으로 복제될** 참이었다.
//
// 기본값은 사용자의 속성이므로 사용자 정보가 나오는 자리에서 나온다. 그러면 서버가
// 첫 렌더에서 답을 알고, 게이트가 사라진다.
//
// ── 왜 쿠키(세션 토큰)에 굽지 않는가 ───────────────────────────────
//
// 훅과 같은 목적("첫 렌더에서 답을 안다")이라면 세션 토큰에 넣는 방법도 있다.
// 안 쓴다. 이유는 둘이다.
//
//   ① **이미 로그인해 있는 사람의 토큰에는 그 값이 없다.** 세션 수명이 7일이라
//      그동안은 서버가 답을 모르고, 그 경우를 받으려면 우리가 방금 없앤 게이트를
//      **다시 남겨야 한다.** 조건 3(게이트 완전 제거)과 정면으로 부딪힌다.
//   ② 구운 값은 낡는다. 아래 조건 2 를 보라.
//
// 요청마다 한 줄 읽는 쪽을 택했다. `actor_area` 는 사람당 한두 행이고 색인이 있다.
//
// ── 낡음(조건 2) ────────────────────────────────────────────────
//
// **낡지 않는다.** 매 요청 읽으므로 소속을 바꾼 다음 요청부터 바로 맞는다.
// 그리고 지금 **앱에는 `actor_area` 를 쓰는 경로가 없다**(읽기 5곳 · 쓰기 0곳).
// 소속 변경은 `scripts/init-db.mjs` 와 마이그레이션에만 있다 — 사람이 화면에서 못 바꾼다.
// 그 사실 자체를 백로그(B-18)에 남긴다. 여기서 만들지 않는다.
//
// ── 경계 ────────────────────────────────────────────────────────
//
// **여기는 「기본값」만 낸다. 「선택지 목록」은 안 낸다** (조건 1).
// 셀렉트에 무엇이 있는지는 계속 `/api/meta/selectors` 가 답한다. 둘을 합치면
// 모든 페이지가 목록 전체를 지고 다니게 되고, 목록이 바뀔 때마다 값이 낡는다.
import { query } from "./db";
import type { SessionUser } from "./types";

export interface UserDefaults {
  /** 내 기본 영역 — `actor_area` 를 sort_order 순으로. 없으면 빈 배열(= 전체 영역). */
  areaIds: number[];
  /** 기본 담당 = 본인. 화면이 `user.id` 를 다시 문자열로 만들지 않게 여기서 함께 낸다. */
  assigneeId: number;
}

export async function userDefaults(user: SessionUser): Promise<UserDefaults> {
  const rows = await query<{ area_id: number }>(
    `SELECT area_id FROM actor_area WHERE actor_id = $1 ORDER BY sort_order, area_id`,
    [user.id]
  );
  return { areaIds: rows.map((r) => r.area_id), assigneeId: user.id };
}
