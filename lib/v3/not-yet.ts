// 아직 안 여는 화면 — **한 파일에 모은다** (MD-P-2026-066 §B).
//
// ── 「없는 것」과 「아직 안 여는 것」은 다른 말이다 (§B-5) ────────
//
// 404 는 「그런 자리가 없다」는 뜻이다. 여기 적힌 것들은 **있고, 만들고 있고,
// 날짜가 정해져 있다.** 404 를 쓰면 읽는 사람이 자기가 주소를 잘못 친 줄 알거나
// 프로그램이 고장 난 줄 안다 — 둘 다 사실이 아니다.
//
// ── `lib/denied.ts` 의 짜임을 그대로 쓴다 (§B-7) ────────────────
//
// 새 방법을 만들지 않는다. 거기와 같은 네 조각이다:
//   ① 열쇠 타입   무엇을 막았는지 가리키는 한 낱말
//   ② 표          열쇠 → 문구. **문장은 이 표 하나에서 나온다**
//   ③ href 만들개  막는 자리가 부른다
//   ④ 읽개        도착한 화면이 부른다. **모르는 열쇠면 `null`** — 아무 말도
//                 안 만든다. 주소는 사람이 손으로 고칠 수 있고, 거기 적힌 것을
//                 그대로 화면에 옮기면 남이 써 준 문장을 우리 목소리로 읽게 된다
//
// ── 푸는 일이 **한 줄 지우기**여야 한다 (§B-10) ─────────────────
//
// 067·068 에서 화면이 서면 이 배열에서 그 줄을 지운다. 그러면
//   · 레일이 자물쇠 대신 진짜 링크를 그리고
//   · 옛 주소가 막음 화면 대신 그 화면으로 가고
//   · 검사기의 「막혀 있다」가 저절로 빨개진다(고칠 곳을 알려 준다)
// 세 가지가 함께 풀린다. 자리가 흩어져 있으면 하나만 풀고 둘을 잊는다.
//
// ── 지금 이 목록에 둘뿐인 이유 ──────────────────────────────────
//
// 066 §B-11 이 이름을 대고 시킨 둘이다 — **내 정보(`/profile`)와 설정
// (`/settings`)**. 지금 v3 레일이 이 둘을 **옛 화면으로 내보내고 있어서**,
// 새 화면을 쓰다가 갑자기 옛 화면이 열린다. 섞여 보이는 것보다 막음 화면이 낫다.
//
// 나머지가 여기 없는 것은 **아직 안 정해졌기 때문이다.** 지시서 §1(필수 아홉)이
// 이번 전달에서 잘려 왔고, 무엇이 필수인지를 **짐작해서 적지 않는다** —
// 잘못 적으면 있어야 할 화면이 조용히 막힌다.
import { V3_BASE } from "./routes";

/** 주소에 실리는 이름. 무엇을 막았는지를 가리킨다. */
export type NotYetKey = "profile" | "settings";

export interface NotYetScreen {
  key: NotYetKey;
  /** 사람이 부르는 이름. 레일과 막음 화면이 같은 낱말을 쓴다 */
  label: string;
  /** ① 무엇인지 — 한 문장 */
  what: string;
  /** 옛 주소. **주소로 직접 들어와도 막으려면** 이게 있어야 한다 (§B-9) */
  old: string;
}

/**
 * ② 표. **줄을 지우면 그 화면이 열린다.**
 *
 * 「언제」와 「돌아갈 길」은 줄마다 안 적는다 — 셋 다 같은 날이고 같은 곳이다.
 * 줄마다 적으면 날짜를 고칠 때 한 줄만 고치고 넘어간다.
 */
export const NOT_YET: NotYetScreen[] = [
  {
    key: "profile", label: "내 정보", old: "/profile",
    what: "이름 · 이메일 · 비밀번호를 보고 고치는 자리입니다.",
  },
  {
    key: "settings", label: "설정", old: "/settings",
    /*
     * **등급 이야기를 안 적는다.** 팀원이 읽으면 「내 등급 때문에 막혔다」로
     * 읽히는데, 지금 막는 이유는 등급이 아니라 **아직 안 만든 것**이다.
     * 같은 상황을 두 가지로 설명하면 어느 쪽이 맞는지 모른다(053 §B-31).
     * 등급 문턱은 화면이 서는 날 제자리로 돌아온다.
     */
    what: "팀 전체에 걸리는 값을 정하는 자리입니다.",
  },
];

/** ② 「언제 열리는지」 (§B-6). **한 곳에서** 온다 — 날짜가 바뀌면 여기만 고친다. */
export const NOT_YET_WHEN = "11월 2일 가오픈 뒤에 엽니다.";

/**
 * ② 「돌아갈 길 하나」 (§B-6). **읽는 사람이 할 수 있는 게 있어야 한다.**
 *
 * 길이 하나인 이유: 둘을 내면 어느 쪽이 「원래 가려던 곳」인지 사람이 고민한다.
 * 로그인한 누구나 볼 수 있는 화면으로 보낸다 — `lib/denied.ts` 가 팀 홈을 고른
 * 것과 같은 판단이다.
 */
export const NOT_YET_BACK = { label: "오늘 화면으로", href: V3_BASE };

/** ③ 막는 자리가 부른다. */
export function notYetHref(key: NotYetKey): string {
  return `${V3_BASE}/not-yet?k=${key}`;
}

/** ④ 도착한 화면이 부른다. **모르는 열쇠면 `null`** — 아무 말도 안 만든다. */
export function notYetOf(key: string | null | undefined): NotYetScreen | null {
  if (!key) return null;
  return NOT_YET.find((s) => s.key === key) ?? null;
}

/**
 * 옛 주소가 막혀 있는가 (§B-9).
 *
 * **레일에서 빼는 것만으로는 안 막힌다** — 주소창에 치면 그대로 열린다.
 * 옛 셸이 이 함수로 한 번 더 묻는다.
 */
export function notYetForOld(path: string): NotYetScreen | null {
  const clean = path.split("?")[0];
  return NOT_YET.find((s) => s.old === clean) ?? null;
}
