// CSV 만들기 — **문자열 다루기만.** 무엇을 내보낼지는 부르는 쪽이 정한다
// (MD-P-2026-066 §C-3).
//
// ── 왜 따로 있는가 ──────────────────────────────────────────────
//
// 「어떤 행을 내보내는가」는 `lib/v3/list-query.ts` 가 정한다(화면과 같은 함수).
// 이 파일은 **고른 행을 글자로 바꾸는 일**만 한다. 둘을 한 파일에 두면
// 「조건」과 「글자 모양」이 섞여서, 한쪽을 고칠 때 다른 쪽을 읽게 된다.
//
// ── 두 가지를 반드시 한다 ──────────────────────────────────────
//
// ① **BOM** (§C-23) — 엑셀은 BOM 이 없으면 UTF-8 을 못 알아보고 한글을 깬다.
//    「눈으로 확인하고 적는다」가 지시라서, 검사기가 첫 세 바이트를 실제로 읽는다.
// ② **수식 주입 막기** (§C-24) — `=` `+` `-` `@` 로 시작하는 값은 엑셀이 **수식**
//    으로 읽는다. 업무 제목이 `=cmd|…` 이면 파일을 연 사람의 엑셀에서 돈다.
//    앞에 따옴표(`'`)를 붙여 **글자임을 못 박는다.**

/** 엑셀이 UTF-8 을 알아보게 하는 세 바이트. 파일 맨 앞에 딱 한 번. */
export const CSV_BOM = "\uFEFF";   // 글자로 적지 않는다 — 소스에서 안 보이면 지운 것과 구별이 안 된다

/** 엑셀이 수식으로 읽기 시작하는 글자들. 탭·캐리지리턴도 같은 취급이다. */
const FORMULA_START = ["=", "+", "-", "@", "\t", "\r"];

/**
 * 한 칸. **수식 주입을 막고**, 쉼표·따옴표·줄바꿈을 감싼다.
 *
 * `null`·`undefined` 는 **빈 칸**이다. 「없음」 같은 말을 여기서 만들지 않는다 —
 * 그건 화면의 말이고, 파일을 받아 다시 계산하는 사람에게는 방해다.
 */
export function csvCell(v: unknown): string {
  if (v === null || v === undefined) return "";
  let s = String(v);
  // ① 수식 주입 — **자르지 않고 무력화한다.** 자르면 제목이 달라져서
  //    화면의 제목과 파일의 제목이 다른 글자가 된다.
  const armed = s.length > 0 && FORMULA_START.includes(s[0]);
  if (armed) s = `'${s}`;
  /*
   * ② 감싸기 — 쉼표·따옴표·줄바꿈이 있으면 따옴표로 싸고 내부 따옴표는 겹친다.
   *
   * **따옴표를 붙인 칸은 무조건 함께 싼다.** 처음에는 안 쌌는데, 그러면 칸이
   * `'=cmd…` 로 맨몸으로 나간다 — 앞의 `'` 가 「글자임을 못 박는 표시」인지
   * 「제목의 첫 글자」인지 받는 쪽이 고를 수 있게 된다. 여는 쪽 프로그램이
   * 어느 쪽으로 읽을지를 우리가 정할 수 없으면 막은 것이 아니다.
   */
  if (armed || /[",\n\r]/.test(s)) s = `"${s.replace(/"/g, '""')}"`;
  return s;
}

/**
 * 머리줄 + 본문. 줄 끝은 `\r\n` — 엑셀이 기대하는 모양이다.
 *
 * 머리줄도 `csvCell` 을 지난다. 열 이름에 쉼표가 들어가는 날 한 줄이 밀린다.
 */
export function toCsv(header: readonly string[], rows: readonly unknown[][]): string {
  const line = (cells: readonly unknown[]) => cells.map(csvCell).join(",");
  return CSV_BOM + [line(header), ...rows.map(line)].join("\r\n") + "\r\n";
}

/**
 * 파일 이름. 날짜를 붙여 **어느 시점의 목록인지** 남긴다 — 이름이 같은 파일이
 * 내려받기 폴더에 쌓이면 어느 것이 오늘 것인지 알 수 없다.
 */
export function csvFilename(stem: string, today: string): string {
  return `${stem}-${today}.csv`;
}
