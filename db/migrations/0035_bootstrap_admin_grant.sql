-- MD-P-2026-041 §A — 최초 관리자 권한 부트스트랩
--
-- ── 무엇을 하는가 ────────────────────────────────────────────────
--
-- **딱 한 사람의 `admin_grant` 를 켠다.** 0034 는 컬럼만 만들었고 아무에게도
-- 권한을 주지 않았다. 그래서 지금 이 시스템에는 관리 화면에 들어갈 수 있는
-- 사람이 **아무도 없다** — 구성원 관리도, 역할 변경도, 계정 발급도 막혀 있다.
-- 그 자물쇠를 한 번 여는 것이 이 파일이다.
--
-- ── 왜 이름이 여기 있는가 ────────────────────────────────────────
--
-- 이름이 나오는 자리는 **이 파일과 되돌리기 파일 둘뿐이다.** 판정 코드는 계속
-- `admin_grant` 만 본다(`lib/types.ts` 의 `isAdmin`). 부트스트랩은 규칙이 아니라
-- **한 번 있었던 사건**이라서, 규칙이 사는 곳이 아니라 이력이 사는 곳에 적는다.
--
-- 「관리자가 0명이면 팀장이 임명할 수 있다」 같은 규칙을 코드에 두지 않는다 —
-- 평소엔 안 쓰이는 우회로가 상시로 열려 있게 된다.
--
-- ── 지시서 정정 ──────────────────────────────────────────────────
--
-- 지시서는 `ac.name` 이었으나 **`actor` 에 `name` 컬럼은 없다.** `display_name` 이다.
-- 그대로 뒀으면 이 파일이 실패하고, 러너가 멈추고, **전 요청이 500 이 된다**
-- (B-29 · 0031 에서 겪은 그대로). 지시서가 규칙을 어기면 지시서가 틀린 것이다(§G).
--
-- ── 안전 ─────────────────────────────────────────────────────────
--
-- · `ac.type = 'human'` 을 **빼지 않는다.** actor 에는 에이전트가 4개 있고,
--   그중 하나에 account 행이 붙는 상태가 생기면 사람이 아닌 것에 권한이 켜진다.
-- · **예외를 던지지 않는다.** 0건이어도 그냥 지나간다. 이름이 틀렸을 때의 벌이
--   서비스 전체 정지여서는 안 된다. 대신 **로그에 남긴다** —
--   0 이면 이름이 틀린 것이고, 그 사실이 로그에만 남아도 다음 판단이 빨라진다.
-- · 이름이 틀렸으면 이 파일을 **고치지 않는다.** 0036 으로 새로 만든다
--   (RUNBOOK 규약 — 이미 적용된 마이그레이션은 안 고친다).
--
-- 되돌리기: db/migrations/rollback/0035_bootstrap_admin_grant_down.sql

DO $$
DECLARE
  turned int;
  admins int;
BEGIN
  UPDATE account a SET admin_grant = true
    FROM actor ac
   WHERE ac.id = a.actor_id
     AND ac.type = 'human'
     AND ac.display_name = '권정혁';
  GET DIAGNOSTICS turned = ROW_COUNT;

  -- 적용 직후 **세어서 남긴다.** 한 값만으로는 「켰다」와 「이름이 틀려 아무것도
  -- 안 켰다」가 안 갈리므로 둘을 같이 적는다.
  --
  -- 아래 조건은 `lib/types.ts` 의 `adminWhereSql` 을 이 시점 기준으로 옮겨 적은
  -- 것이다. 마이그레이션은 지나간 사건이라 코드에서 불러올 수 없다 — 판정이
  -- 나중에 바뀌어도 **이 줄은 그때의 기준으로 남는 것이 맞다.**
  SELECT count(*) INTO admins
    FROM account a2 JOIN actor ac2 ON ac2.id = a2.actor_id
   WHERE (a2.role = 'admin' OR a2.admin_grant = true) AND ac2.is_active = true;

  RAISE NOTICE '[0035] 부트스트랩 — 권한 켠 계정 %건 · 적용 후 활성 관리자 %명', turned, admins;

  IF admins = 0 THEN
    RAISE NOTICE '[0035] ⚠ 활성 관리자가 0명이다. 이름이 틀렸을 가능성이 크다. 관리 화면에 들어갈 사람이 없다. 이 파일을 고치지 말고 0036 으로 새로 만들 것';
  END IF;
END $$;
