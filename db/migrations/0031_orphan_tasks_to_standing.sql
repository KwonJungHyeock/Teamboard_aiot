-- MD-P-2026-032 §A3 — 프로젝트 없는 업무를 상시 프로젝트로 (배치 ③/③)
--
-- ── 추정은 실행하지 않는다 ────────────────────────────────────────
--
-- `docs/audit/032/A3-귀속대상.md` 에 「제목에서 읽히는 추정 프로젝트」 열이 있지만
-- **여기서는 쓰지 않는다.** 추정만으로 프로젝트와 영역 둘을 한 번에 바꾸면
-- 되돌리기 어렵고, 틀렸을 때 어디까지 되돌려야 하는지가 흐려진다.
--
-- **전부 자기 영역의 상시 프로젝트로** 보낸다. 그 뒤 사람이 화면에서 옮긴다 —
-- §B 가 하려는 일이 바로 그 이동을 3초로 만드는 것이다(프로젝트 버튼 하나를
-- 누르면 영역·목표가 따라온다). **사람이 화면에서 하는 것이 더 정확하고 더 빠르다.**
--
-- ── 건수를 조건으로 넣지 않는다 ───────────────────────────────────
--
-- 「19건」도 「20건」도 적지 않는다. 로컬 시드와 프로덕션의 수가 다르고,
-- 이 마이그레이션은 프로덕션에서 돈다. 사후 확인에서
-- **「프로젝트 없는 활성 업무 = 0」** 만 보면 된다.
--
-- ── 영역은 바뀌지 않는다 ──────────────────────────────────────────
--
-- 같은 영역의 상시 프로젝트로만 보내므로 `trg_task_area_match` 를 건드리지 않는다.
-- `task.area_id` 는 그대로다.
--
-- ── ⚠ 개인 업무는 옮기지 않는다 ───────────────────────────────────
--
-- **이 줄이 없어서 프로덕션이 멈췄다.** 처음 판에는 `visibility` 조건이 없었고,
-- 러너가 `task_private_no_project` 위반으로 던졌다. 마이그레이션은 모든 DB 접근
-- 앞에서 도므로 **팀 전원이 로그인하지 못했다.**
--
--   0025_task_visibility.sql:29
--   CHECK (visibility <> 'private' OR project_id IS NULL)
--
-- 규칙은 0025 가 이미 정해 뒀다 — 프로젝트는 팀 단위다. 개인 업무가 프로젝트에
-- 들어가면 프로젝트 상세·진척·목표 롤업을 통해 팀에게 새어 나간다.
-- 그러므로 **개인 업무는 프로젝트 없이 남는 것이 맞다.** 예외가 아니라 설계다.
--
-- 따라서 사후 확인의 「프로젝트 없는 활성 업무 = 0」도 틀렸다. 옳은 기준은
-- **「프로젝트 없는 활성 *팀* 업무 = 0」**이다. 개인 업무는 남는다.
-- 같은 이유로 B-25(`task.project_id` NOT NULL)는 **영원히 불가능하다.**
UPDATE task t
   SET project_id = p.id
  FROM project p
 WHERE t.project_id IS NULL
   AND t.is_active = true
   AND t.visibility <> 'private'
   AND p.area_id = t.area_id
   AND p.type = 'standing';

-- `task.project_id` 를 NOT NULL 로 만들지 않는다 — **아직은 아니다.**
-- 경로 하나가 빠졌을 때 500 이 나느니 프로젝트 없이 남는 편이 낫다.
-- 한 달 뒤 별도 판단 (B-25).
--
-- 되돌리기 — 이 마이그레이션이 붙인 것만 뗀다(상시 프로젝트에 붙은 것만).
--   UPDATE task t SET project_id = NULL
--     FROM project p
--    WHERE t.project_id = p.id AND p.type = 'standing';
--   ※ 그 뒤 사람이 화면에서 옮긴 것까지 함께 떨어진다. 배치 ③ 직후에만 안전하다.
