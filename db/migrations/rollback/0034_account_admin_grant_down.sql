-- MD-P-2026-039 §A — 0034 되돌리기
--
-- ⚠ **이 되돌리기는 켜 둔 권한을 통째로 날립니다.**
--    컬럼을 지우므로 누가 권한을 갖고 있었는지도 함께 사라집니다.
--    0033 되돌리기(역할을 내리면 되는 것)와 성격이 다릅니다 —
--    저쪽은 값을 옮기는 일이고, 이쪽은 **자리 자체를 없애는 일**입니다.
--
-- 그러니 지우기 전에 **목록을 먼저 뜨십시오.** 다시 켤 때 이 목록이 유일한 근거입니다.
--
--   SELECT a.display_name, ac.email, ac.role
--     FROM account ac JOIN actor a ON a.id = ac.actor_id
--    WHERE ac.admin_grant = true;                          -- 보관할 것
--
-- 목록이 비어 있어도 확인은 하십시오. 「0건이었다」도 확인을 낸 것입니다(§G) —
-- 안 보고 지우는 것과 보고 지우는 것은 다릅니다.
--
-- ── 되돌린 뒤에 남는 것 ──────────────────────────────────────────
--
-- `role='admin'` 인 계정은 그대로 관리자입니다. 판정이 role 도 보기 때문에
-- **관리자가 0명이 되지는 않습니다** — 대표 계정이 admin 이면 그렇습니다.
-- 대표 계정이 없는 상태에서 이걸 되돌리면 **관리자가 0명이 되고, 그때는
-- 아무도 계정을 발급할 수 없으며 멤버 관리 화면에 들어갈 수도 없습니다.**
-- 되돌리기 전에 반드시 세십시오:
--
--   SELECT count(*) FROM account WHERE role = 'admin';     -- 0 이면 되돌리지 말 것
--
-- ── 되돌리기 시한 ────────────────────────────────────────────────
--
-- **두지 않습니다.** 컬럼을 더했을 뿐 데이터를 만들지도 옮기지도 않았습니다
-- (0032 · 0033 과 같은 판단). 다만 위 두 확인은 시한과 무관하게 **매번** 필요합니다.
--
-- `schema_migrations` 에서 줄을 **지우지 않습니다**(RUNBOOK 규약).
-- 다시 적용해야 하면 **새 번호로 정방향 마이그레이션을 씁니다.**

ALTER TABLE account DROP COLUMN IF EXISTS admin_grant;
