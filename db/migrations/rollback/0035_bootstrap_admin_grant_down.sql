-- MD-P-2026-041 §A — 0035 되돌리기
--
-- ⚠ **이것은 그 사람의 관리자 권한을 끕니다.**
--    그 사람이 유일한 관리자였다면 되돌린 직후 **관리자가 0명이 되고,
--    아무도 구성원 관리 화면에 들어갈 수 없습니다.** 계정 발급도, 역할 변경도
--    막힙니다. 화면에는 다시 켤 길이 없습니다 — 되돌린 사람이 DB 에서 다시
--    켜야 합니다.
--
-- 그러니 되돌리기 전에 **먼저 세십시오.**
--
--   SELECT count(*) FROM account a JOIN actor ac ON ac.id = a.actor_id
--    WHERE (a.role = 'admin' OR a.admin_grant = true) AND ac.is_active = true;
--
--   -- 위가 1이면, 이걸 되돌리는 순간 0이 됩니다. 다른 관리자를 먼저 세우십시오.
--
-- 0 건이 나와도 확인은 하십시오. 「0건이었다」도 확인을 낸 것입니다(§G).
--
-- ── 되돌리기 시한 ────────────────────────────────────────────────
--
-- **두지 않습니다.** 컬럼도 표도 안 건드리고 값 하나를 되돌릴 뿐입니다.
-- 다만 위 확인은 시한과 무관하게 **매번** 필요합니다.
--
-- `schema_migrations` 에서 줄을 **지우지 않습니다**(RUNBOOK 규약).
-- 다시 적용해야 하면 **새 번호로 정방향 마이그레이션을 씁니다.**
--
-- ⚠ 이 파일은 `admin_grant` 를 **false 로 되돌릴 뿐**, 「원래 어땠는지」로
--    되돌리지 않습니다. 0035 가 돌기 전에 그 사람의 권한이 이미 켜져 있었다면
--    (0034 직후엔 전원 false 라 그럴 일이 없지만) 이 되돌리기는 그 상태까지
--    지웁니다. 되돌리기 전 목록을 뜨라고 한 이유입니다.

UPDATE account a SET admin_grant = false
  FROM actor ac
 WHERE ac.id = a.actor_id
   AND ac.type = 'human'
   AND ac.display_name = '권정혁';
