-- MD-P-2026-032 §B 착수 전 — 영역당 상시 프로젝트는 **하나뿐이다**
--
-- ── 왜 필요한가 ───────────────────────────────────────────────────
--
-- §B 의 「상시」 버튼은 `type='standing' AND area_id = <영역>` 으로 프로젝트를
-- 찾는다. 지금은 영역당 정확히 하나라 답이 하나지만, **코드가 그것을 전제하면
-- 다음에 하나 더 만들어지는 순간 조용히 틀린다.** 둘 중 아무거나 고르고,
-- 아무 말도 안 하고, 화면은 멀쩡해 보인다.
--
-- 전제를 코드에 두지 않고 **DB 가 참으로 만들게** 한다.
--
-- ── 부분 유니크 인덱스인 이유 ─────────────────────────────────────
--
-- `goal` 프로젝트는 한 영역에 여럿일 수 있고 **그게 정상이다**(지금도 그렇다).
-- 그러므로 `UNIQUE (area_id)` 가 아니라 `WHERE type = 'standing'` 이다.
-- 이 조건이 없으면 goal 프로젝트를 두 번째로 만들 수 없게 되어 앱이 멈춘다.
--
-- ── 실행 전 확인 (PM 이 Neon 에서 완료) ───────────────────────────
--
--   SELECT area_id, count(*) FROM project
--    WHERE type = 'standing' GROUP BY area_id HAVING count(*) > 1;
--   → 0행. 로컬·프로덕션 둘 다.
--
-- **중복이 하나라도 있으면 이 인덱스 생성은 실패한다.** 그리고 마이그레이션
-- 실패는 러너를 통해 전면 장애가 된다(B-29). 그래서 확인이 먼저였다.
-- 리허설에서 중복을 일부러 만들어 **정말 실패하는지**까지 봤다
-- (`scripts/repro-0032.mjs`) — 확인이 형식이 아니었음을 그것으로 남긴다.
--
-- ── CONCURRENTLY 를 쓰지 않는 이유 ────────────────────────────────
--
-- `CREATE INDEX CONCURRENTLY` 는 트랜잭션 안에서 못 쓴다. 러너는 파일마다
-- `BEGIN`/`COMMIT` 으로 감싸므로 여기서는 쓸 수 없다.
-- `project` 는 열 행 남짓이라 잠금 시간이 문제되지 않는다. 표가 커지면
-- 그때는 러너 밖에서 따로 만들어야 한다 — **지금 결정을 미래에 물려주지 않는다.**
--
-- 되돌리기: DROP INDEX IF EXISTS project_standing_one_per_area;
CREATE UNIQUE INDEX IF NOT EXISTS project_standing_one_per_area
    ON project (area_id)
 WHERE type = 'standing';
