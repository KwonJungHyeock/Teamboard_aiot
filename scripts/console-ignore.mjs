// 콘솔에서 **안 세는 것** — 한 곳에 모은다 (MD-P-2026-061 §D-14).
//
// ── 왜 한 파일인가 ────────────────────────────────────────────────
//
// 검사기마다 「이건 빼자」를 흩어 놓으면 서른 개 파일에 서른 개의 예외가 생기고,
// 그때부터 **경고를 센다는 말이 뜻을 잃는다.** 무엇을 안 보기로 했는지가
// 곧 무엇을 못 보는지다(§G 059). 그러니 한 곳에서, 세면서 자란다.
//
// ── 줄을 더하는 규칙 ──────────────────────────────────────────────
//
//   · **이유 없는 줄은 넣지 않는다.** 「시끄러워서」는 이유가 아니다.
//   · 우리 코드가 낸 것은 여기 넣지 않는다. 고치거나, 목록으로 올려 지시를 받는다.
//   · 검사기가 **스스로 만든** 오류(일부러 낸 404·400)도 여기 넣지 않는다 —
//     그건 그 검사기 안에서 따로 세야 한다(v3-bulk ③짝 · v3-detail ⑲ 참고).
//     여기 넣으면 다른 검사기에서 난 진짜 404 까지 같이 눈감게 된다.
//
// 지금 세 줄이다. 늘어나면 왜 늘었는지가 이 파일에 남는다.

export const IGNORED_CONSOLE = [
  {
    /*
     * 크롬이 내는 안내다. 우리 코드가 아니다.
     * sticky/fixed 헤더가 있는 화면에서 `scrollIntoView` 를 부르면, 브라우저가
     * 「가려질 수 있어 자동 스크롤을 건너뛴다」고 알린다. 동작은 정상이고
     * 고칠 자리도 우리 쪽에 없다 — sticky 헤더를 거두는 것은 설계를 되돌리는 일이다.
     * 처음 걸린 자리: agent-usage 2건 · open-due-screen 2건 · first-run 4건 ·
     * saved-view 3건 (060 전량 실행).
     */
    re: /Skipping auto-scroll behavior due to `?position: (sticky|fixed)`?/,
    why: "크롬이 내는 안내 — sticky 헤더 + scrollIntoView. 우리 코드가 아니고 동작은 정상이다",
  },
  {
    /*
     * 개발 서버에서만 나오는 리액트 개발도구 권유. 배포본에는 없다.
     */
    re: /Download the React DevTools/,
    why: "dev 서버에서만 나오는 리액트 안내 — 배포본에는 없다",
  },
  {
    /*
     * Next dev 의 빠른 새로고침 안내. 코드를 고치면 나온다.
     */
    re: /\[Fast Refresh\]/,
    why: "Next dev 의 빠른 새로고침 안내 — 배포본에는 없다",
  },
];

/**
 * 이 줄을 무시하기로 했는가. 무시하면 **왜 무시하는지**를 돌려준다.
 *
 * 불리언이 아니라 이유를 돌려주는 이유: 부르는 쪽이 「무시 3건」이 아니라
 * 「무엇을 왜 3건 무시했는지」를 찍을 수 있어야 한다.
 */
export function ignoredWhy(text) {
  for (const r of IGNORED_CONSOLE) if (r.re.test(text)) return r.why;
  return null;
}
